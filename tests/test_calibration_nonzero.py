"""
Test: calibration curves MUST NOT be all-zero-sample (M6 calibration sprint).

Regression guard for the 2026-10-03 zero-station bug: `data/calibration_curves.json`
was regenerated by hand in an all-zero shape — every (station, market-type,
direction) cell carried `global.n == 0`. That artifact parses and loads fine, so
`HourlyCalibration` reported "Loaded calibration curves for 21 stations" while the
runner logged "Calibration complete: 0 stations calibrated" — the M5/KBOS-KSAT
zero-station shape, and the reason the M1->M2->M4 chain produced no evaluated days.

The test has two halves:
  1. Synthetic: the validator/guard detects an all-zero curves dict and accepts a
     nonzero one. (Deterministic, no disk read — always runnable.)
  2. Live: if the committed `data/calibration_curves.json` exists, assert it is
     NOT all-zero. Skips (not fails) when the artifact is absent, so a clean
     checkout without the generated file does not red the gate.
"""

import json
import os
import sys
import unittest

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from scripts.build_calibration_curves import zero_sample_stations  # noqa: E402

CURVES_PATH = os.path.join(_REPO_ROOT, "data", "calibration_curves.json")

STATIONS = [
    "KNYC", "KLAX", "KPHX", "KDFW", "KATL", "KAUS", "KBOS", "KDCA", "KDEN",
    "KHOU", "KLAS", "KMDW", "KMIA", "KMSP", "KMSY", "KOKC", "KPHL", "KSAT",
    "KSEA", "KSFO",
]


def _zero_cell():
    return {"bins": {}, "global": {"n": 0, "win_rate": 0.5}}


def _all_zero_curves():
    return {
        s: {
            "HIGH": {"up": _zero_cell(), "down": _zero_cell()},
            "LOW": {"up": _zero_cell(), "down": _zero_cell()},
        }
        for s in STATIONS
    }


def _healthy_curves():
    c = _all_zero_curves()
    # Give every station a nonzero HIGH/up global — enough to clear the guard.
    for s in STATIONS:
        c[s]["HIGH"]["up"]["global"] = {"n": 42, "win_rate": 0.61}
    return c


class ZeroSampleValidatorTests(unittest.TestCase):
    def test_all_zero_detected(self):
        zero = zero_sample_stations(_all_zero_curves(), STATIONS)
        self.assertEqual(len(zero), len(STATIONS))

    def test_single_zero_station_detected(self):
        curves = _healthy_curves()
        curves["KBOS"] = {
            "HIGH": {"up": _zero_cell(), "down": _zero_cell()},
            "LOW": {"up": _zero_cell(), "down": _zero_cell()},
        }
        zero = zero_sample_stations(curves, STATIONS)
        self.assertEqual(zero, ["KBOS"])

    def test_healthy_has_no_zero_stations(self):
        zero = zero_sample_stations(_healthy_curves(), STATIONS)
        self.assertEqual(zero, [])


class LiveCurvesArtifactTests(unittest.TestCase):
    def test_committed_curves_not_all_zero(self):
        if not os.path.exists(CURVES_PATH):
            self.skipTest("calibration_curves.json not generated in this checkout")
        with open(CURVES_PATH) as f:
            curves = json.load(f)
        present = [s for s in STATIONS if s in curves]
        self.assertTrue(present, "curves artifact has no known stations")
        zero = zero_sample_stations(curves, present)
        self.assertEqual(
            zero, [],
            f"calibration_curves.json is zero-sample for {zero} "
            f"(M5/KBOS-KSAT shape) — rerun scripts/build_calibration_curves.py",
        )


if __name__ == "__main__":
    unittest.main()
